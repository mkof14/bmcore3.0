function merge(target, patch) {
  for (const [k, v] of Object.entries(patch)) {
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      target[k] = target[k] || {};
      merge(target[k], v);
    } else {
      target[k] = v;
    }
  }
}

